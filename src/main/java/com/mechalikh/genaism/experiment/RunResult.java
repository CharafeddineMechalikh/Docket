	/**
	 * The device and queue counters of one replica.
	 */
	public static class ReplicaStats {

		/** Engine identifier of the replica. */
		public final int replicaId;
		/** Model the replica serves. */
		public final String modelId;
		/** Device the replica runs on. */
		public final String deviceId;
		/** Prefill steps executed. */
		public final long prefillSteps;
		/** Decode iterations executed. */
		public final long decodeIterations;
		/** Mean number of sequences per iteration. */
		public final double meanBatchSize;
		/** Largest batch seen. */
		public final int peakBatchSize;
		/** Sequences suspended to free cache. */
		public final long preemptions;
		/** Cache reservations that were refused. */
		public final long cacheRefusals;
		/** Instants where the replica held requests but could not start a step. */
		public final long stalledSteps;
		/** Largest fraction of the cache pool in use. */
		public final double peakCacheOccupancy;
		/** Blocks the pool holds in total. */
		public final int totalBlocks;
		/** Tokens the pool can hold in total. */
		public final int capacityTokens;
		/** Energy the device integrated, in joules. */
		public final double totalEnergyJoule;
		/** Energy of the active intervals, in joules. */
		public final double activeEnergyJoule;
		/** Energy of the idle intervals, in joules. */
		public final double idleEnergyJoule;
		/** Fraction of the duration the device spent executing. */
		public final double utilisation;
		/** Seconds the device was charged as executing. */
		public final double activeSeconds;
		/** Seconds the device was charged as idle. */
		public final double idleSeconds;
		/** Power drawn while holding no work, in watts. */
		public final double idlePowerWatts;
		/** Power drawn while executing, in watts. */
		public final double activePowerWatts;

		/**
		 * Reads the counters of a replica after the run ended.
		 *
		 * @param replica         the replica
		 * @param durationSeconds simulated duration the utilisation is measured over
		 */
		public ReplicaStats(ReplicaServer replica, double durationSeconds) {
			replicaId = replica.getId();
			modelId = replica.getModel().getId();
			deviceId = replica.getDevice().getId();
			prefillSteps = replica.getPrefillSteps();
			decodeIterations = replica.getDecodeIterations();
			meanBatchSize = replica.meanBatchSize();
			peakBatchSize = replica.getPeakBatchSize();
			preemptions = replica.getPreemptions();
			cacheRefusals = replica.getCacheRefusals();
			stalledSteps = replica.getStalledSteps();
			totalBlocks = replica.getPool().getTotalBlocks();
			peakCacheOccupancy = totalBlocks == 0 ? 0 : (double) replica.getPool().peakUsedBlocks() / totalBlocks;
			capacityTokens = replica.getPool().capacityTokens();
			GpuPowerModel power = replica.getPower();
			totalEnergyJoule = power.totalJoule();
			activeEnergyJoule = power.activeEnergyJoule();
			idleEnergyJoule = power.idleEnergyJoule();
			utilisation = power.utilisation(durationSeconds);
			activeSeconds = power.getActiveSeconds();
			idleSeconds = power.getIdleSeconds();
			idlePowerWatts = power.idlePowerWatts();
			activePowerWatts = power.activePowerWatts();
		}

		/**
		 * Returns a line describing the replica, for the console.
		 *
		 * @return the description
		 */
		public String describe() {
			return String.format(Locale.ROOT,
					"replica %d (%s on %s): %d prefill steps, %d iterations, batch mean %.2f peak %d, "
							+ "preemptions %d, cache refusals %d, stalls %d, peak cache %.1f%% of %d blocks, "
							+ "utilisation %.1f%%, energy %.3f J",
					replicaId, modelId, deviceId, prefillSteps, decodeIterations, meanBatchSize, peakBatchSize,
					preemptions, cacheRefusals, stalledSteps, peakCacheOccupancy * 100, totalBlocks,
					utilisation * 100, totalEnergyJoule);
		}
	}

	/**
	 * The service level answers of one service class.
	 */
	public static class ServiceClassSlo {

		/** Name of the class. */
		public final String serviceClass;
		/** Requests of the class, whatever their outcome. */
		public int offered;
		/** Completed requests of the class. */
		public int completed;
		/** Applicable and met answers per objective. */
		protected final Map<String, int[]> counters = new LinkedHashMap<>();

		/**
		 * Creates the counters of a class.
		 *
		 * @param serviceClass the class name
		 */
		public ServiceClassSlo(String serviceClass) {
			this.serviceClass = serviceClass;
			for (String objective : new String[] { "ttft", "e2e", "tpot", "all" })
				counters.put(objective, new int[2]);
		}

		/**
		 * Adds one request to the class.
		 *
		 * @param request a recorded request
		 */
		public void add(InferenceRequest request) {
			offered++;
			if (request.getState() == RequestState.COMPLETED)
				completed++;
			count(request, "ttft", SloChecks.ttftMet(request));
			count(request, "e2e", SloChecks.endToEndMet(request));
			count(request, "tpot", SloChecks.tpotMet(request));
			count(request, "all", SloChecks.allMet(request));
		}

		/**
		 * Records one objective answer.
		 *
		 * @param request   the request the answer belongs to
		 * @param objective the objective name
		 * @param answer    the answer, {@code null} when not applicable
		 */
		protected void count(InferenceRequest request, String objective, Boolean answer) {
			if (answer == null)
				return;
			int[] counter = counters.get(objective);
			counter[0]++;
			if (answer)
				counter[1]++;
		}

		/**
		 * Returns the attainment of an objective, over the requests of the class that stated it.
		 *
		 * @param objective one of {@code ttft}, {@code e2e}, {@code tpot}, {@code all}
		 * @return ratio in [0, 1], {@code Double.NaN} when no request of the class stated it
		 */
		public double attainment(String objective) {
			int[] counter = counters.get(objective);
			return counter[0] == 0 ? Double.NaN : (double) counter[1] / counter[0];
		}

		/**
		 * Returns how many requests of the class stated the objective.
		 *
		 * @param objective one of {@code ttft}, {@code e2e}, {@code tpot}, {@code all}
		 * @return the applicable count
		 */
		public int applicable(String objective) {
			return counters.get(objective)[0];
		}

		/**
		 * Returns how many of those met it.
		 *
		 * @param objective one of {@code ttft}, {@code e2e}, {@code tpot}, {@code all}
		 * @return the met count
		 */
		public int met(String objective) {
			return counters.get(objective)[1];
		}

		/**
		 * Returns a one-line description of the class with its offered, completed and all-met
		 * counts, for the console.
		 *
		 * @return the description
		 */
		@Override
		public String toString() {
			return serviceClass + ": offered " + offered + ", completed " + completed + ", all-met "
					+ counters.get("all")[1] + "/" + counters.get("all")[0];
		}
	}

	/**
	 * Returns a one-line description of the repetition, including the time-to-first-token p99, for
	 * the console.
	 *
	 * @return the description
	 */
	@Override
	public String toString() {
		return "RunResult[rep=" + repetition + ", seed=" + seed + ", offered=" + arrivedRequests + ", completed="
				+ completedRequests + ", ttft p99=" + stat("ttft_s").percentile(99) + "]";
	}

