#!/usr/bin/env bash
# Shared setup for the example scripts: move to the repository root, decide the classpath
# separator of this platform, and expose a `docket` function that runs the simulator with the
# example policies on the classpath.
#
# The policies in examples/*/src are compiled into target/test-classes by `mvn test-compile`,
# so they never enter the published jar but are reachable from a scenario that names them.
set -eu

ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
cd "$ROOT"

case "$(uname -s)" in
	MINGW* | MSYS* | CYGWIN*) SEP=';' ;;
	*) SEP=':' ;;
esac

if [ ! -d target/classes ] || [ ! -d target/test-classes ]; then
	echo "build the project and the examples first: mvn -q test-compile" >&2
	exit 1
fi

CLASSPATH="target/classes${SEP}target/test-classes"
for jar in target/lib/*.jar; do
	CLASSPATH="$CLASSPATH${SEP}$jar"
done
export CLASSPATH

# Runs one scenario. Results land under <root>/<experiment.name>/, which is how the CLI writes
# them; the caller decides where <root> is.
docket() {
	java -cp "$CLASSPATH" com.mechalikh.docket.cli.Main "$@"
}

# Keeps the four small artifacts of a run and drops the per-request table, which is large and
# can be regenerated by running the scenario.
keep_artifacts() {
	rm -rf "$1/rep01"
}
